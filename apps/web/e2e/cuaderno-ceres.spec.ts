import { expect, test } from "@playwright/test";
import { answerProfile, delimitField } from "./helpers/field";

test("R20: captura confirmada, agenda, memoria de Ceres y run nuevo", async ({ page }) => {
  const status=await (await page.request.get("/api/v1/assistant/status")).json();
  expect(status.model,"Arrancar tests.e2e_app:app; nunca usar un LLM real").toBe("simulado-pruebas");
  await page.setViewportSize({width:375,height:812});
  await page.goto("/");
  await page.goto("/app");
  await delimitField(page);
  await answerProfile(page);
  await page.getByRole("button",{name:"Crear cuenta y guardar"}).click();
  await page.getByRole("button",{name:"Regístrate"}).click();
  await page.getByLabel("Email").fill(`r20-${Date.now()}@ceres.test`);
  await page.getByLabel(/Contraseña/).fill("clave-r20-segura-123");
  await page.getByRole("button",{name:"Crear cuenta",exact:true}).click();
  await expect(page.getByText("Guardado en tu cuenta")).toBeVisible();
  await page.getByRole("navigation",{name:"Módulos"}).getByRole("link",{name:"Cuaderno",exact:true}).click();
  await page.getByLabel("Cuenta lo que hiciste",{exact:true}).fill("Coseché 4000 kg de maíz en 1 ha y vendí 1000 kg a 1.2 soles.");
  await page.getByRole("button",{name:"Enviar texto"}).click();
  const proposal=page.getByRole("region",{name:"Propuesta de registros"});
  await expect(proposal.getByRole("heading",{name:"¿Guardo esto?"})).toBeVisible();
  const parcels=await (await page.request.get("/api/v1/parcels")).json(); const pid=parcels.items[0].id;
  expect((await (await page.request.get(`/api/v1/parcels/${pid}/notebook`)).json()).items).toHaveLength(0);
  await proposal.getByLabel("Cantidad vendida (kg)").fill("1200");
  await proposal.getByRole("button",{name:"Sí, guardar"}).click();
  await expect(proposal).toHaveCount(0);
  await expect(page.locator("article")).toHaveCount(2);
  await page.reload();
  await expect(page.locator("article")).toHaveCount(2);
  await page.getByText("Registrar con formulario", { exact: true }).click(); // formulario plegado: voz primero
  await page.getByLabel("Tipo de registro").selectOption("agenda");
  await page.getByRole("button",{name:"Nuevo registro"}).click();
  await page.getByLabel("Labor o recordatorio").fill("Confirmar turno de riego");
  await page.getByRole("button",{name:"Guardar registro",exact:true}).click();
  await expect(page.getByRole("button",{name:"Marcar hecho"})).toBeVisible();
  await page.getByRole("button",{name:"Marcar hecho"}).click();
  await expect(page.getByRole("button",{name:"Marcar hecho"})).toHaveCount(0);
  await page.getByRole("navigation",{name:"Módulos"}).getByRole("link",{name:"Ceres",exact:true}).click();
  await page.getByLabel("Tu mensaje para Ceres").fill("¿Qué recuerdas de mi venta?");
  await page.getByRole("button",{name:"Enviar texto"}).click();
  await expect(page.getByText(/Recuerdo tu venta confirmada: 1200 kg/)).toBeVisible();
  const before=await (await page.request.get(`/api/v1/parcels/${pid}/recommendations`)).json();
  await page.getByLabel("Tu mensaje para Ceres").fill("Simula con 1000 m3 de agua mensual");
  await page.getByRole("button",{name:"Enviar texto"}).click();
  await expect(page.getByRole("heading",{name:"Nuevo escenario del motor"})).toBeVisible();
  const after=await (await page.request.get(`/api/v1/parcels/${pid}/recommendations`)).json();
  expect(after.items).toHaveLength(before.items.length+1);
  await page.getByText("Ver comparación del escenario",{exact:true}).click();
  await expect(page.locator(".strategy-card").nth(2)).toBeVisible();
  expect(await page.evaluate(()=>document.documentElement.scrollWidth-innerWidth)).toBeLessThanOrEqual(0);
});
